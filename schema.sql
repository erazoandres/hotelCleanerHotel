CREATE OR REPLACE FUNCTION public.registrar_cambio_asignacion_habitacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.id_personal_asignado IS NOT NULL THEN
      INSERT INTO public.asignaciones_habitacion (id_habitacion, id_personal, tipo_limpieza)
      VALUES (NEW.id_habitacion, NEW.id_personal_asignado, NEW.tipo_limpieza_asignada);
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.id_personal_asignado IS DISTINCT FROM OLD.id_personal_asignado THEN
    UPDATE public.asignaciones_habitacion
    SET liberado_en = NOW()
    WHERE id_habitacion = NEW.id_habitacion AND liberado_en IS NULL;

    IF NEW.id_personal_asignado IS NOT NULL THEN
      INSERT INTO public.asignaciones_habitacion (id_habitacion, id_personal, tipo_limpieza)
      VALUES (NEW.id_habitacion, NEW.id_personal_asignado, NEW.tipo_limpieza_asignada);
    END IF;
  ELSIF NEW.id_personal_asignado IS NOT NULL
      AND NEW.tipo_limpieza_asignada IS DISTINCT FROM OLD.tipo_limpieza_asignada THEN
    UPDATE public.asignaciones_habitacion
    SET tipo_limpieza = NEW.tipo_limpieza_asignada
    WHERE id_habitacion = NEW.id_habitacion AND liberado_en IS NULL;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS habitaciones_registrar_cambio_asignacion ON public.habitaciones;
CREATE TRIGGER habitaciones_registrar_cambio_asignacion
AFTER INSERT OR UPDATE OF id_personal_asignado, tipo_limpieza_asignada ON public.habitaciones
FOR EACH ROW
EXECUTE FUNCTION public.registrar_cambio_asignacion_habitacion();


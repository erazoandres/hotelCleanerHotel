-- Devuelve el perfil asociado al usuario Supabase autenticado.
CREATE OR REPLACE FUNCTION public.perfil_aseador()
RETURNS TABLE (id_personal TEXT, nombre TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth, pg_temp
AS $$
  SELECT p.id_personal, p.nombre
  FROM public.personal p
  WHERE p.auth_user_id = auth.uid()
    AND p.activo IS TRUE
    AND auth.jwt() -> 'app_metadata' ->> 'role' = 'hotel_cleaner';
$$;

-- Devuelve solo las habitaciones del trabajador autenticado.
CREATE OR REPLACE FUNCTION public.habitaciones_aseador()
RETURNS TABLE (
  id_habitacion TEXT,
  estado TEXT,
  nombre_huesped TEXT,
  plan_limpieza TEXT,
  detalles_limpieza TEXT,
  tipo_limpieza_asignada TEXT
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth, pg_temp
AS $$
  SELECT h.id_habitacion, h.estado, h.nombre_huesped, h.plan_limpieza,
         h.detalles_limpieza, h.tipo_limpieza_asignada
  FROM public.personal p
  JOIN public.habitaciones h ON h.id_personal_asignado = p.id_personal
  WHERE p.auth_user_id = auth.uid()
    AND p.activo IS TRUE
    AND auth.jwt() -> 'app_metadata' ->> 'role' = 'hotel_cleaner'
  ORDER BY h.id_habitacion;
$$;

-- El trabajador solo puede finalizar una habitacion que tiene asignada.
CREATE OR REPLACE FUNCTION public.finalizar_habitacion_aseador(
  p_id_habitacion TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth, pg_temp
AS $$
DECLARE
  trabajador RECORD;
  tipo TEXT;
BEGIN
  SELECT p.id_personal, p.nombre
  INTO trabajador
  FROM public.personal p
  WHERE p.auth_user_id = auth.uid()
    AND p.activo IS TRUE
    AND auth.jwt() -> 'app_metadata' ->> 'role' = 'hotel_cleaner';

  IF trabajador.id_personal IS NULL THEN
    RAISE EXCEPTION 'No hay una cuenta de aseo activa asociada a esta sesion.';
  END IF;

  UPDATE public.habitaciones h
  SET estado = 'finalizado',
      actualizado_en = NOW()
  WHERE h.id_habitacion = p_id_habitacion
    AND h.id_personal_asignado = trabajador.id_personal
    AND h.estado <> 'finalizado'
  RETURNING h.tipo_limpieza_asignada INTO tipo;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La habitacion no esta asignada o ya fue finalizada.';
  END IF;

  INSERT INTO public.trabajos_limpieza (
    id_personal, nombre_personal, id_habitacion, tipo_limpieza
  )
  VALUES (trabajador.id_personal, trabajador.nombre, p_id_habitacion, tipo);

  INSERT INTO public.eventos (
    id_habitacion, estado, accion, responsable, id_personal, tipo_limpieza
  )
  VALUES (
    p_id_habitacion, 'finalizado', 'Limpieza finalizada',
    trabajador.nombre, trabajador.id_personal, tipo
  );

  RETURN TRUE;
END;
$$;

-- Guarda cada asignacion y su liberacion en el historial.
CREATE OR REPLACE FUNCTION public.registrar_cambio_asignacion_habitacion()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.id_personal_asignado IS NOT DISTINCT FROM OLD.id_personal_asignado
       AND NEW.tipo_limpieza_asignada IS NOT DISTINCT FROM OLD.tipo_limpieza_asignada THEN
      RETURN NEW;
    END IF;

    UPDATE public.asignaciones_habitacion
    SET liberado_en = NOW()
    WHERE id_habitacion = NEW.id_habitacion
      AND liberado_en IS NULL;
  END IF;

  IF NEW.id_personal_asignado IS NOT NULL THEN
    INSERT INTO public.asignaciones_habitacion (
      id_habitacion, id_personal, tipo_limpieza
    )
    VALUES (
      NEW.id_habitacion, NEW.id_personal_asignado,
      NEW.tipo_limpieza_asignada
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS habitaciones_registrar_cambio_asignacion
  ON public.habitaciones;
CREATE TRIGGER habitaciones_registrar_cambio_asignacion
AFTER INSERT OR UPDATE OF id_personal_asignado, tipo_limpieza_asignada
ON public.habitaciones
FOR EACH ROW
EXECUTE FUNCTION public.registrar_cambio_asignacion_habitacion();


-- Esquema nuevo en español para Supabase.
-- No inserta habitaciones, personal ni movimientos de ejemplo.

CREATE TABLE IF NOT EXISTS public.personal (
  id_personal TEXT PRIMARY KEY,
  nombre TEXT NOT NULL CHECK (length(trim(nombre)) > 0),
  contacto TEXT NOT NULL CHECK (
    contacto ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    OR (
      contacto ~ '^[+0-9() .-]+$'
      AND length(regexp_replace(contacto, '[^0-9]', '', 'g')) >= 7
    )
  ),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE TABLE IF NOT EXISTS public.personal_credenciales (
  id_personal TEXT PRIMARY KEY
    REFERENCES public.personal(id_personal) ON DELETE CASCADE,
  password_hash TEXT NOT NULL,
  requiere_rotacion BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.personal_credenciales
  ADD COLUMN IF NOT EXISTS requiere_rotacion BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
DECLARE
  crypto_schema TEXT;
BEGIN
  SELECT n.nspname
  INTO crypto_schema
  FROM pg_extension AS e
  JOIN pg_namespace AS n ON n.oid = e.extnamespace
  WHERE e.extname = 'pgcrypto';

  IF crypto_schema IS NULL THEN
    RAISE EXCEPTION 'La extensión pgcrypto no está disponible.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'personal'
      AND column_name = 'password'
  ) THEN
    EXECUTE format(
      'INSERT INTO public.personal_credenciales (id_personal, password_hash, requiere_rotacion)
       SELECT id_personal,
              %1$I.crypt(COALESCE(NULLIF(password, ''''), encode(%1$I.gen_random_bytes(18), ''hex'')),
                         %1$I.gen_salt(''bf'', 12)),
              TRUE
       FROM public.personal
       ON CONFLICT (id_personal) DO UPDATE
       SET requiere_rotacion = TRUE',
      crypto_schema
    );
    ALTER TABLE public.personal DROP COLUMN password;
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.habitaciones (
  id_habitacion TEXT PRIMARY KEY,
  estado TEXT NOT NULL
    CHECK (estado IN ('libre', 'ocupada', 'pendiente', 'limpieza')),
  nombre_huesped TEXT,
  plan_limpieza TEXT,
  detalles_limpieza TEXT,
  id_personal_asignado TEXT REFERENCES public.personal(id_personal) ON DELETE SET NULL,
  tipo_limpieza_asignada TEXT,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.habitaciones ALTER COLUMN estado DROP DEFAULT;
ALTER TABLE public.habitaciones DROP CONSTRAINT IF EXISTS habitaciones_estado_check;
ALTER TABLE public.habitaciones
  ADD CONSTRAINT habitaciones_estado_check
  CHECK (estado IN ('libre', 'ocupada', 'pendiente', 'limpieza', 'finalizado'));

CREATE TABLE IF NOT EXISTS public.asignaciones_habitacion (
  id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_habitacion TEXT NOT NULL REFERENCES public.habitaciones(id_habitacion) ON DELETE RESTRICT,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal) ON DELETE RESTRICT,
  tipo_limpieza TEXT,
  asignado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  liberado_en TIMESTAMPTZ,
  CHECK (liberado_en IS NULL OR liberado_en >= asignado_en)
);

CREATE UNIQUE INDEX IF NOT EXISTS asignaciones_una_activa_por_habitacion
  ON public.asignaciones_habitacion (id_habitacion)
  WHERE liberado_en IS NULL;

CREATE INDEX IF NOT EXISTS asignaciones_historial_personal
  ON public.asignaciones_habitacion (id_personal, asignado_en DESC);

CREATE TABLE IF NOT EXISTS public.asistencias (
  id_asistencia TEXT PRIMARY KEY,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal) ON DELETE RESTRICT,
  nombre_personal TEXT NOT NULL,
  entrada TIMESTAMPTZ NOT NULL,
  salida TIMESTAMPTZ,
  CHECK (salida IS NULL OR salida > entrada)
);

CREATE UNIQUE INDEX IF NOT EXISTS asistencias_una_abierta_por_personal
  ON public.asistencias (id_personal)
  WHERE salida IS NULL;

CREATE INDEX IF NOT EXISTS asistencias_historial_personal
  ON public.asistencias (id_personal, entrada DESC);

CREATE TABLE IF NOT EXISTS public.eventos (
  id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_habitacion TEXT NOT NULL REFERENCES public.habitaciones(id_habitacion) ON DELETE RESTRICT,
  estado TEXT NOT NULL CHECK (estado IN ('libre', 'ocupada', 'pendiente', 'limpieza')),
  accion TEXT NOT NULL,
  nombre_huesped TEXT,
  responsable TEXT,
  id_personal TEXT REFERENCES public.personal(id_personal) ON DELETE SET NULL,
  tipo_limpieza TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.eventos DROP CONSTRAINT IF EXISTS eventos_estado_check;
ALTER TABLE public.eventos
  ADD CONSTRAINT eventos_estado_check
  CHECK (estado IN ('libre', 'ocupada', 'pendiente', 'limpieza', 'finalizado'));

ALTER TABLE public.eventos ADD COLUMN IF NOT EXISTS nombre_huesped TEXT;
ALTER TABLE public.eventos ALTER COLUMN responsable DROP NOT NULL;

CREATE TABLE IF NOT EXISTS public.trabajos_limpieza (
  id_trabajo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal) ON DELETE RESTRICT,
  nombre_personal TEXT NOT NULL,
  id_habitacion TEXT NOT NULL REFERENCES public.habitaciones(id_habitacion) ON DELETE RESTRICT,
  tipo_limpieza TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.novedades (
  id_novedad TEXT PRIMARY KEY,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal) ON DELETE RESTRICT,
  nombre_personal TEXT NOT NULL,
  fecha DATE NOT NULL,
  tipo TEXT NOT NULL,
  etiqueta TEXT NOT NULL,
  notas TEXT,
  minutos_extra INTEGER CHECK (minutos_extra >= 0),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION public.buscar_aseador(p_telefono TEXT, p_password TEXT)
RETURNS TABLE (id_personal TEXT, nombre TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
  WITH coincidencias AS (
    SELECT p.id_personal, p.nombre
    FROM public.personal AS p
    JOIN public.personal_credenciales AS c USING (id_personal)
    WHERE p.activo IS TRUE
      AND c.password_hash = crypt(p_password, c.password_hash)
      AND c.requiere_rotacion IS FALSE
      AND length(regexp_replace(COALESCE(p_telefono, ''), '[^0-9]', '', 'g')) >= 7
      AND regexp_replace(p.contacto, '[^0-9]', '', 'g') =
          regexp_replace(COALESCE(p_telefono, ''), '[^0-9]', '', 'g')
  )
  SELECT c.id_personal, c.nombre
  FROM coincidencias AS c
  WHERE (SELECT count(*) FROM coincidencias) = 1;
$$;

CREATE OR REPLACE FUNCTION public.crear_aseador(
  p_id_personal TEXT,
  p_nombre TEXT,
  p_contacto TEXT,
  p_password TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
BEGIN
  IF COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'hotel_admin' THEN
    RAISE EXCEPTION 'Permiso denegado.';
  END IF;
  IF length(p_password) < 12 THEN
    RAISE EXCEPTION 'La clave temporal debe tener al menos 12 caracteres.';
  END IF;

  INSERT INTO public.personal (id_personal, nombre, contacto, activo)
  VALUES (p_id_personal, p_nombre, p_contacto, TRUE);

  INSERT INTO public.personal_credenciales (id_personal, password_hash)
  VALUES (p_id_personal, crypt(p_password, gen_salt('bf', 12)));
END;
$$;

CREATE OR REPLACE FUNCTION public.regenerar_clave_aseador(p_id_personal TEXT)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
DECLARE
  v_password TEXT := encode(gen_random_bytes(18), 'hex');
BEGIN
  IF COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'hotel_admin' THEN
    RAISE EXCEPTION 'Permiso denegado.';
  END IF;

  UPDATE public.personal_credenciales
  SET password_hash = crypt(v_password, gen_salt('bf', 12)),
      requiere_rotacion = FALSE,
      actualizado_en = NOW()
  WHERE id_personal = p_id_personal;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontró la ficha de credenciales del aseador.';
  END IF;

  RETURN v_password;
END;
$$;

CREATE OR REPLACE FUNCTION public.autenticar_aseador(p_telefono TEXT, p_password TEXT)
RETURNS TABLE (id_personal TEXT, nombre TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
  SELECT a.id_personal, a.nombre
  FROM public.buscar_aseador(p_telefono, p_password) AS a;
$$;

CREATE OR REPLACE FUNCTION public.habitaciones_aseador(p_telefono TEXT, p_password TEXT)
RETURNS TABLE (
  id_habitacion TEXT,
  estado TEXT,
  nombre_huesped TEXT,
  plan_limpieza TEXT,
  detalles_limpieza TEXT,
  tipo_limpieza_asignada TEXT
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
  SELECT h.id_habitacion, h.estado, h.nombre_huesped, h.plan_limpieza,
         h.detalles_limpieza, h.tipo_limpieza_asignada
  FROM public.buscar_aseador(p_telefono, p_password) AS a
  JOIN public.habitaciones AS h ON h.id_personal_asignado = a.id_personal
  ORDER BY h.id_habitacion;
$$;

CREATE OR REPLACE FUNCTION public.finalizar_habitacion_aseador(
  p_telefono TEXT,
  p_password TEXT,
  p_id_habitacion TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
DECLARE
  v_id_personal TEXT;
  v_nombre TEXT;
  v_tipo_limpieza TEXT;
BEGIN
  SELECT a.id_personal, a.nombre
  INTO v_id_personal, v_nombre
  FROM public.buscar_aseador(p_telefono, p_password) AS a;

  IF v_id_personal IS NULL THEN
    RAISE EXCEPTION 'Credenciales inválidas.';
  END IF;

  UPDATE public.habitaciones AS h
  SET estado = 'finalizado', actualizado_en = NOW()
  WHERE h.id_habitacion = p_id_habitacion
    AND h.id_personal_asignado = v_id_personal
    AND h.estado <> 'finalizado'
  RETURNING h.tipo_limpieza_asignada INTO v_tipo_limpieza;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La habitación no está asignada a este aseador o ya fue finalizada.';
  END IF;

  INSERT INTO public.trabajos_limpieza (
    id_personal, nombre_personal, id_habitacion, tipo_limpieza
  )
  VALUES (v_id_personal, v_nombre, p_id_habitacion, v_tipo_limpieza);

  INSERT INTO public.eventos (
    id_habitacion, estado, accion, responsable, id_personal, tipo_limpieza
  )
  VALUES (
    p_id_habitacion, 'finalizado', 'Limpieza finalizada', v_nombre,
    v_id_personal, v_tipo_limpieza
  );

  RETURN TRUE;
END;
$$;


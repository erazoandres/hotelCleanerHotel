-- Base de datos del control de habitaciones.
-- Compatible con la aplicacion React y Supabase.
-- No borra tablas ni datos. Para empezar vacio, crea un proyecto Supabase nuevo.

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

-- Personal del hotel.
CREATE TABLE IF NOT EXISTS public.personal (
  id_personal TEXT PRIMARY KEY,
  nombre TEXT NOT NULL,
  contacto TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.personal
  ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE public.personal
  ADD COLUMN IF NOT EXISTS creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- Habitaciones, estado actual, huesped y personal asignado.
CREATE TABLE IF NOT EXISTS public.habitaciones (
  id_habitacion TEXT PRIMARY KEY,
  estado TEXT NOT NULL CHECK (
    estado IN ('libre', 'ocupada', 'pendiente', 'limpieza', 'finalizado')
  ),
  nombre_huesped TEXT,
  plan_limpieza TEXT,
  detalles_limpieza TEXT,
  id_personal_asignado TEXT REFERENCES public.personal(id_personal) ON DELETE SET NULL,
  tipo_limpieza_asignada TEXT,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.habitaciones
  ADD COLUMN IF NOT EXISTS nombre_huesped TEXT;
ALTER TABLE public.habitaciones
  ADD COLUMN IF NOT EXISTS plan_limpieza TEXT;
ALTER TABLE public.habitaciones
  ADD COLUMN IF NOT EXISTS detalles_limpieza TEXT;
ALTER TABLE public.habitaciones
  ADD COLUMN IF NOT EXISTS id_personal_asignado TEXT
  REFERENCES public.personal(id_personal) ON DELETE SET NULL;
ALTER TABLE public.habitaciones
  ADD COLUMN IF NOT EXISTS tipo_limpieza_asignada TEXT;
ALTER TABLE public.habitaciones
  ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW();

ALTER TABLE public.habitaciones
  DROP CONSTRAINT IF EXISTS habitaciones_estado_check;
ALTER TABLE public.habitaciones
  ADD CONSTRAINT habitaciones_estado_check
  CHECK (estado IN ('libre', 'ocupada', 'pendiente', 'limpieza', 'finalizado'));

-- Historial de asignacion de habitaciones a personal.
CREATE TABLE IF NOT EXISTS public.asignaciones_habitacion (
  id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_habitacion TEXT NOT NULL REFERENCES public.habitaciones(id_habitacion),
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal),
  tipo_limpieza TEXT,
  asignado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  liberado_en TIMESTAMPTZ,
  CHECK (liberado_en IS NULL OR liberado_en >= asignado_en)
);

CREATE UNIQUE INDEX IF NOT EXISTS asignaciones_una_activa_por_habitacion
  ON public.asignaciones_habitacion (id_habitacion)
  WHERE liberado_en IS NULL;
CREATE INDEX IF NOT EXISTS asignaciones_historial_personal
  ON public.asignaciones_habitacion (id_personal, asignado_en DESC);

-- Entradas y salidas del personal.
CREATE TABLE IF NOT EXISTS public.asistencias (
  id_asistencia TEXT PRIMARY KEY,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal),
  nombre_personal TEXT NOT NULL,
  entrada TIMESTAMPTZ NOT NULL,
  salida TIMESTAMPTZ,
  CHECK (salida IS NULL OR salida > entrada)
);

CREATE UNIQUE INDEX IF NOT EXISTS asistencias_una_abierta_por_personal
  ON public.asistencias (id_personal)
  WHERE salida IS NULL;
CREATE INDEX IF NOT EXISTS asistencias_historial_personal
  ON public.asistencias (id_personal, entrada DESC);

-- Historial de cambios y movimientos.
CREATE TABLE IF NOT EXISTS public.eventos (
  id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_habitacion TEXT NOT NULL REFERENCES public.habitaciones(id_habitacion),
  estado TEXT NOT NULL CHECK (
    estado IN ('libre', 'ocupada', 'pendiente', 'limpieza', 'finalizado')
  ),
  accion TEXT NOT NULL,
  nombre_huesped TEXT,
  responsable TEXT,
  id_personal TEXT REFERENCES public.personal(id_personal) ON DELETE SET NULL,
  tipo_limpieza TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.eventos
  ADD COLUMN IF NOT EXISTS nombre_huesped TEXT;
ALTER TABLE public.eventos
  ALTER COLUMN responsable DROP NOT NULL;
ALTER TABLE public.eventos
  DROP CONSTRAINT IF EXISTS eventos_estado_check;
ALTER TABLE public.eventos
  ADD CONSTRAINT eventos_estado_check
  CHECK (estado IN ('libre', 'ocupada', 'pendiente', 'limpieza', 'finalizado'));
CREATE INDEX IF NOT EXISTS eventos_habitacion_fecha
  ON public.eventos (id_habitacion, creado_en DESC);

-- Trabajos terminados por personal de aseo.
CREATE TABLE IF NOT EXISTS public.trabajos_limpieza (
  id_trabajo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal),
  nombre_personal TEXT NOT NULL,
  id_habitacion TEXT NOT NULL REFERENCES public.habitaciones(id_habitacion),
  tipo_limpieza TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS trabajos_limpieza_fecha
  ON public.trabajos_limpieza (creado_en DESC);

-- Novedades del personal.
CREATE TABLE IF NOT EXISTS public.novedades (
  id_novedad TEXT PRIMARY KEY,
  id_personal TEXT NOT NULL REFERENCES public.personal(id_personal),
  nombre_personal TEXT NOT NULL,
  fecha DATE NOT NULL,
  tipo TEXT NOT NULL,
  etiqueta TEXT NOT NULL,
  notas TEXT,
  minutos_extra INTEGER CHECK (minutos_extra >= 0),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS novedades_personal_fecha
  ON public.novedades (id_personal, fecha DESC);

-- Claves del personal: solo se guarda el hash, nunca la clave original.
CREATE TABLE IF NOT EXISTS public.personal_credenciales (
  id_personal TEXT PRIMARY KEY
    REFERENCES public.personal(id_personal) ON DELETE CASCADE,
  password_hash TEXT NOT NULL,
  requiere_rotacion BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.personal_credenciales
  ADD COLUMN IF NOT EXISTS requiere_rotacion BOOLEAN NOT NULL DEFAULT FALSE;

-- Si ya existia public.personal.password, migra las claves a hashes y obliga a
-- regenerarlas antes de permitir otro inicio de sesion del personal.
DO $$
DECLARE
  esquema_crypto TEXT;
BEGIN
  SELECT n.nspname
  INTO esquema_crypto
  FROM pg_extension e
  JOIN pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname = 'pgcrypto';

  IF esquema_crypto IS NULL THEN
    RAISE EXCEPTION 'No se pudo habilitar la extension pgcrypto.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'personal'
      AND column_name = 'password'
  ) THEN
    EXECUTE format(
      'INSERT INTO public.personal_credenciales
         (id_personal, password_hash, requiere_rotacion)
       SELECT id_personal,
         %1$I.crypt(
           COALESCE(NULLIF(password, ''''), %1$I.encode(%1$I.gen_random_bytes(18), ''hex'')),
           %1$I.gen_salt(''bf'', 12)
         ),
         TRUE
       FROM public.personal
       ON CONFLICT (id_personal) DO UPDATE
         SET requiere_rotacion = TRUE',
      esquema_crypto
    );
    ALTER TABLE public.personal DROP COLUMN password;
  END IF;
END;
$$;

-- Comprueba el rol guardado por el administrador en app_metadata de Supabase.
CREATE OR REPLACE FUNCTION public.es_administrador_hotel()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
AS $$
  SELECT COALESCE(
    auth.jwt() -> 'app_metadata' ->> 'role' = 'hotel_admin',
    FALSE
  );
$$;

-- Comprueba el telefono y la clave del personal. Esta funcion interna no se
-- puede llamar directamente desde el navegador.
CREATE OR REPLACE FUNCTION public.buscar_aseador(
  p_telefono TEXT,
  p_password TEXT
)
RETURNS TABLE (id_personal TEXT, nombre TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
  WITH coincidencias AS (
    SELECT p.id_personal, p.nombre
    FROM public.personal p
    JOIN public.personal_credenciales c USING (id_personal)
    WHERE p.activo IS TRUE
      AND c.requiere_rotacion IS FALSE
      AND c.password_hash = crypt(p_password, c.password_hash)
      AND length(regexp_replace(COALESCE(p_telefono, ''), '[^0-9]', '', 'g')) >= 7
      AND regexp_replace(p.contacto, '[^0-9]', '', 'g') =
          regexp_replace(COALESCE(p_telefono, ''), '[^0-9]', '', 'g')
  )
  SELECT c.id_personal, c.nombre
  FROM coincidencias c
  WHERE (SELECT count(*) FROM coincidencias) = 1;
$$;

-- El administrador crea una ficha y una clave temporal.
CREATE OR REPLACE FUNCTION public.crear_aseador(
  p_id_personal TEXT,
  p_nombre TEXT,
  p_contacto TEXT,
  p_password TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
BEGIN
  IF NOT public.es_administrador_hotel() THEN
    RAISE EXCEPTION 'Solo un administrador puede crear personal.';
  END IF;
  IF length(p_password) < 12 THEN
    RAISE EXCEPTION 'La clave temporal debe tener al menos 12 caracteres.';
  END IF;
  IF length(regexp_replace(COALESCE(p_contacto, ''), '[^0-9]', '', 'g')) < 7 THEN
    RAISE EXCEPTION 'El telefono no es valido.';
  END IF;

  INSERT INTO public.personal (id_personal, nombre, contacto, activo)
  VALUES (p_id_personal, trim(p_nombre), trim(p_contacto), TRUE);

  INSERT INTO public.personal_credenciales (id_personal, password_hash)
  VALUES (p_id_personal, crypt(p_password, gen_salt('bf', 12)));
END;
$$;

-- El administrador crea una clave nueva para un trabajador.
CREATE OR REPLACE FUNCTION public.regenerar_clave_aseador(p_id_personal TEXT)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
DECLARE
  nueva_clave TEXT := encode(gen_random_bytes(18), 'hex');
BEGIN
  IF NOT public.es_administrador_hotel() THEN
    RAISE EXCEPTION 'Solo un administrador puede cambiar la clave.';
  END IF;

  UPDATE public.personal_credenciales
  SET password_hash = crypt(nueva_clave, gen_salt('bf', 12)),
      requiere_rotacion = FALSE,
      actualizado_en = NOW()
  WHERE id_personal = p_id_personal;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontraron credenciales para este trabajador.';
  END IF;

  RETURN nueva_clave;
END;
$$;

-- Inicio de sesion del personal de aseo.
CREATE OR REPLACE FUNCTION public.autenticar_aseador(
  p_telefono TEXT,
  p_password TEXT
)
RETURNS TABLE (id_personal TEXT, nombre TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
  SELECT a.id_personal, a.nombre
  FROM public.buscar_aseador(p_telefono, p_password) a;
$$;

-- Devuelve solo las habitaciones asignadas al trabajador autenticado.
CREATE OR REPLACE FUNCTION public.habitaciones_aseador(
  p_telefono TEXT,
  p_password TEXT
)
RETURNS TABLE (
  id_habitacion TEXT,
  estado TEXT,
  nombre_huesped TEXT,
  plan_limpieza TEXT,
  detalles_limpieza TEXT,
  tipo_limpieza_asignada TEXT
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
  SELECT h.id_habitacion, h.estado, h.nombre_huesped, h.plan_limpieza,
         h.detalles_limpieza, h.tipo_limpieza_asignada
  FROM public.buscar_aseador(p_telefono, p_password) a
  JOIN public.habitaciones h ON h.id_personal_asignado = a.id_personal
  ORDER BY h.id_habitacion;
$$;

-- El trabajador solo puede finalizar una habitacion que tiene asignada.
CREATE OR REPLACE FUNCTION public.finalizar_habitacion_aseador(
  p_telefono TEXT,
  p_password TEXT,
  p_id_habitacion TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, extensions, public, pg_temp
AS $$
DECLARE
  trabajador RECORD;
  tipo TEXT;
BEGIN
  SELECT a.id_personal, a.nombre
  INTO trabajador
  FROM public.buscar_aseador(p_telefono, p_password) a;

  IF trabajador.id_personal IS NULL THEN
    RAISE EXCEPTION 'Telefono o clave incorrectos.';
  END IF;

  UPDATE public.habitaciones h
  SET estado = 'finalizado',
      actualizado_en = NOW()
  WHERE h.id_habitacion = p_id_habitacion
    AND h.id_personal_asignado = trabajador.id_personal
    AND h.estado <> 'finalizado'
  RETURNING h.tipo_limpieza_asignada INTO tipo;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La habitacion no esta asignada o ya fue finalizada.';
  END IF;

  INSERT INTO public.trabajos_limpieza (
    id_personal, nombre_personal, id_habitacion, tipo_limpieza
  )
  VALUES (trabajador.id_personal, trabajador.nombre, p_id_habitacion, tipo);

  INSERT INTO public.eventos (
    id_habitacion, estado, accion, responsable, id_personal, tipo_limpieza
  )
  VALUES (
    p_id_habitacion, 'finalizado', 'Limpieza finalizada',
    trabajador.nombre, trabajador.id_personal, tipo
  );

  RETURN TRUE;
END;
$$;

-- Guarda cada asignacion y su liberacion en el historial.
CREATE OR REPLACE FUNCTION public.registrar_cambio_asignacion_habitacion()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.id_personal_asignado IS NOT DISTINCT FROM OLD.id_personal_asignado
       AND NEW.tipo_limpieza_asignada IS NOT DISTINCT FROM OLD.tipo_limpieza_asignada THEN
      RETURN NEW;
    END IF;

    UPDATE public.asignaciones_habitacion
    SET liberado_en = NOW()
    WHERE id_habitacion = NEW.id_habitacion
      AND liberado_en IS NULL;
  END IF;

  IF NEW.id_personal_asignado IS NOT NULL THEN
    INSERT INTO public.asignaciones_habitacion (
      id_habitacion, id_personal, tipo_limpieza
    )
    VALUES (
      NEW.id_habitacion, NEW.id_personal_asignado,
      NEW.tipo_limpieza_asignada
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS habitaciones_registrar_cambio_asignacion
  ON public.habitaciones;
CREATE TRIGGER habitaciones_registrar_cambio_asignacion
AFTER INSERT OR UPDATE OF id_personal_asignado, tipo_limpieza_asignada
ON public.habitaciones
FOR EACH ROW
EXECUTE FUNCTION public.registrar_cambio_asignacion_habitacion();


DO $$
DECLARE
  tabla TEXT;
  politica TEXT;
BEGIN
  FOREACH tabla IN ARRAY ARRAY[
    'personal', 'habitaciones', 'asignaciones_habitacion',
    'asistencias', 'eventos', 'trabajos_limpieza', 'novedades'
  ]
  LOOP
    FOR politica IN
      SELECT policyname
      FROM pg_policies
      WHERE schemaname = 'public' AND tablename = tabla
    LOOP
      EXECUTE format('DROP POLICY %I ON public.%I', politica, tabla);
    END LOOP;

    EXECUTE format(
      'CREATE POLICY "Administradores gestionan datos" ON public.%I
       FOR ALL TO authenticated
       USING (public.es_administrador_hotel())
       WITH CHECK (public.es_administrador_hotel())',
      tabla
    );
  END LOOP;
END;
$$;

